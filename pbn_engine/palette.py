def load_palette_from_json(path: str) -> list[PigmentColor]:
    """Загрузить реальную палитру Дениса из JSON вида:
    [{"name": "...", "rgb": [R, G, B]}, ...]
    Этим файлом плацехолдер выше заменяется без изменения остального кода.
    """
    import json

    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    return [PigmentColor(item["name"], tuple(item["rgb"])) for item in data]
