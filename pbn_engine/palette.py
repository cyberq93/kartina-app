"""
Палитра базовых красок.

ВАЖНО: цвета ниже — ПЛАЦЕХОЛДЕР (типовой стартовый набор акриловых красок
для бюджетных наборов "картина по номерам"), приблизительные sRGB-значения
"на глаз". Это не калибровка под реальные тюбики Дениса.

Как заменить на реальные данные:
1. Сфотографировать мазок каждой реальной краски на белом листе при дневном
   свете (без вспышки, не против окна).
2. Взять средний цвет мазка (можно даже пипеткой в любом графическом
   редакторе) и вписать его как rgb=(R, G, B) ниже, вместо текущих значений.
3. Название (name) — то, что должно печататься на листе палитры
   (бренд + название цвета, как на тюбике).

Движок смешивания (mixing.py) не привязан к конкретным цветам — он работает
с любым списком PigmentColor, поэтому замена палитры не требует правок
в остальном коде.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class PigmentColor:
    name: str
    rgb: tuple[int, int, int]  # 0-255, sRGB


